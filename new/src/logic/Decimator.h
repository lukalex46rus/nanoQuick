#pragma once

// ============================================================================
// Decimator — усредняющее прореживание (boxcar) для оверсэмплинга.
// Один feed-путь, два выходных тира: разрешение (про) и шумоподавление (средний).
// ----------------------------------------------------------------------------
// Платформа: не зависит (нет регистров; чистая логика).
// Ресурсы:   — (только типы; состояние — 6 байт на объект).
// Предусл.:  вход 10-битный (0..1023, АЦП 328P); поток выборок равномерный;
//            для про-тира нужен ~1 LSB шума (dither), иначе ENOB не растёт.
// Контекст:  — (тип; usable в main+ISR, если сам объект не разделяется).
// Огранич.:  EXTRA 0..4 (N = 1, 4, 16, 64, 256). Выход — (10 + EXTRA) бит:
//            sum >> EXTRA оставляет 2^EXTRA в знаменателе как «дробную
//            часть» шкалы. Это НЕ среднее (среднее — sum >> 2*EXTRA), а
//            среднее, масштабированное в (10+EXTRA)-битную шкалу.
//            Даёт разрешение, не абсолютную точность: INL/offset АЦП
//            остаются. Накопитель sum — uint32_t; максимум 4^4 * 1023 = 261888.
// Зависит:   base/Status.h, <stdint.h>.
// ============================================================================
#include <stdint.h>
#include "../base/Status.h"

namespace logic {

// Один feed-путь, два тира:
//   feed().value — нормализованный результат (sum >> EXTRA), валиден при ok();
//   sum          — сырая сумма N выборок (поле), читается после ok(),
//                  ДО следующего feed()/reset() (иначе обнулится).
// EXTRA 0..4 (N=1..256). Даёт разрешение, не точность; нужен ~1 LSB шума.
template<uint8_t EXTRA>
struct Decimator {
    static_assert(EXTRA <= 4, "EXTRA 0..4");
    static constexpr uint8_t  SHIFT_N = (uint8_t)(2 * EXTRA);   // N = 1 << SHIFT_N
    static constexpr uint16_t N       = (uint16_t)(1u << SHIFT_N);
    static constexpr uint8_t  SHIFT_O = EXTRA;                  // 10 + EXTRA бит

    uint32_t sum;
    uint16_t cnt;

    // constexpr с явными нулями: гарантирует инициализацию (в отличие от
    // = default для агрегата, который оставил бы поля неинициализированными).
    constexpr Decimator() : sum(0), cnt(0) {}

    // Подать выборку; ok когда блок из N выборок децимирован.
    // value — (10+EXTRA)-бит (про-тир). Для 10-бит среднего: value >> EXTRA.
    // Сырая sum доступна после ok(), до следующего feed()/reset().
    base::Result<uint16_t> feed(uint16_t s) {
        sum += s;
        if (++cnt < N)
            return base::Result<uint16_t>{ 0, base::err(base::Err::NotReady) };
        uint16_t v = (uint16_t)(sum >> SHIFT_O);
        sum = 0; cnt = 0;
        return base::Result<uint16_t>{ v, base::ok() };
    }

    void reset() { sum = 0; cnt = 0; }
};

} // namespace logic